/**
 * Cool / lookalike alphabets.
 *
 * These swap Latin letters for Unicode characters from other scripts that
 * *look* similar. They are not installed typefaces and not trademarked font
 * names — the output is still plain text, and screen readers will announce
 * the underlying script (Cherokee, CJK, Runic, …).
 *
 * Maps are curated for visual resemblance and everyday font coverage. Letters
 * without a decent twin are omitted so `applyMap` can leave them as Latin
 * (see `partialCoverage` on the style).
 */

export type LookalikeMap = Record<string, string>;

/** Copy uppercase glyphs onto lowercase when no dedicated small form exists. */
export function withLower(
  upper: LookalikeMap,
  lower?: LookalikeMap,
): LookalikeMap {
  const map: LookalikeMap = { ...upper };
  for (let i = 0; i < 26; i++) {
    const cap = String.fromCharCode(65 + i);
    const small = String.fromCharCode(97 + i);
    if (map[small] === undefined) {
      map[small] = lower?.[small] ?? upper[cap] ?? small;
    }
  }
  if (lower) Object.assign(map, lower);
  return map;
}

