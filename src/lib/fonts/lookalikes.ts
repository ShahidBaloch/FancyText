/** All-small Cherokee, including letters that were typed as capitals. */
export const CHEROKEE_SMALL_MAP = withLower(
  Object.fromEntries(
    Object.entries(CHEROKEE_UPPER).map(([ch]) => [
      ch,
      CHEROKEE_LOWER[ch.toLowerCase()] ?? CHEROKEE_UPPER[ch]!,
    ]),
  ),
  CHEROKEE_LOWER,
);

